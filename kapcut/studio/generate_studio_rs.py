 "pub fn animate_text(args: &Value) -> Value {",
 "    let text = args.get(\"text\").and_then(Value::as_str).unwrap_or(\"TEXT\");",
 "    let aid = args.get(\"animator\").and_then(Value::as_str).unwrap_or(\"burst\");",
