 "pub fn invent_style(args: &Value) -> Value {",
 "    let description = args.get(\"description\").and_then(Value::as_str).unwrap_or(\"\").to_ascii_lowercase();",
 "    let title = args.get(\"title\").and_then(Value::as_str).unwrap_or(\"TITLE\");",
