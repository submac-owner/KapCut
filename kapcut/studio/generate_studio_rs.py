 "fn style_of(el: &Value) -> Value {",
 "    let mut s = json!({ \"kind\": el.get(\"kind\").and_then(Value::as_str).unwrap_or(\"square\").to_ascii_lowercase() });",
 "    if let Some(obj) = s.as_object_mut() {",
