 "    let mut commands: Vec<Value> = Vec::new();",
 "    for (i, word) in words.iter().enumerate() {",
 "        let at = start + i as f64 * stagger;",
 "        let life = (dur - i as f64 * stagger).max(0.2);",
 "        commands.push(json!({ \"op\":\"addTextClip\", \"start\":at, \"duration\":life,",
